let current = "start";
function render() {
    document.getElementById("gdTabs").innerHTML = GUIDE.map(
        (g) => `<button type="button" class="gd-tab ${g.key === current ? "active" : ""}" data-k="${g.key}"><i class="bx ${g.icon}"></i> ${g.label}</button>`,
    ).join("");
    document.getElementById("gdBody").innerHTML = (GUIDE.find((g) => g.key === current) || GUIDE[0]).html();
    document.querySelectorAll("#gdTabs [data-k]").forEach((b) =>
        b.addEventListener("click", () => {
            current = b.dataset.k;
            history.replaceState(null, "", `#${current}`);
            render();
            window.scrollTo(0, 0);
        }),
    );
    window.furaSetCrumbs?.(["Як працювати", GUIDE.find((g) => g.key === current)?.label || ""]);
}

document.addEventListener("DOMContentLoaded", async () => {
    const {
        data: { session },
    } = await sbClient.auth.getSession();
    if (!session) {
        window.location.href = "login.html";
        return;
    }
    document.body.style.visibility = "visible";
    sbClient.auth.onAuthStateChange((event) => {
        if (event === "SIGNED_OUT") window.location.href = "login.html";
    });
    const h = location.hash.slice(1);
    if (GUIDE.some((g) => g.key === h)) current = h;
    render();
});
